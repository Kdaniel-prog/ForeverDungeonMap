"""Boss levels from QuestieDB's WoW Forever NPC database (GPLv3,
https://github.com/Questie/QuestieDB data/Forever/foreverNpcDB.lua).

Usage:
    python -I tools/import_boss_levels.py <foreverNpcDB.lua> <Generated.lua> <out BossLevels.lua>

Matches bosses by npcID, then by exact name. Writes
ns.BOSS_LEVELS = { [instanceID] = { [bossName] = { min, max, elite } } }.
"""
import re
import sys

NPCDB, GENERATED, OUT = sys.argv[1], sys.argv[2], sys.argv[3]

by_id, by_name = {}, {}
row = re.compile(r"^\[(\d+)\] = \{'((?:[^'\\]|\\.)*)',(-?\d+|nil),(-?\d+|nil),(\d+|nil),(\d+|nil),(\d+|nil),")
for line in open(NPCDB, encoding="utf-8"):
    m = row.match(line)
    if not m:
        continue
    npc_id, name = int(m.group(1)), m.group(2).replace("\\'", "'")
    lo, hi, rank = m.group(5), m.group(6), m.group(7)
    if lo == "nil":
        continue
    rec = (int(lo), int(hi) if hi != "nil" else int(lo), int(rank) if rank != "nil" else 0)
    by_id[npc_id] = rec
    by_name.setdefault(name.lower(), rec)

out, missing = {}, []
cur = None
for line in open(GENERATED, encoding="utf-8"):
    m = re.match(r"\s*\[(\d+)\] = \{ -- ", line)
    if m:
        cur = int(m.group(1))
        continue
    if line.startswith("ns.WINGS"):
        break
    m = re.match(r'\s*\{ name = "((?:[^"\\]|\\.)*)"(.*)\},', line)
    if not m or cur is None:
        continue
    name = m.group(1).replace('\\"', '"')
    nid = re.search(r"npcID = (\d+)", m.group(2))
    rec = by_id.get(int(nid.group(1))) if nid else None
    rec = rec or by_name.get(name.lower())
    if rec:
        out.setdefault(cur, {})[name] = rec
    else:
        missing.append((cur, name))

lines = [
    "-- GENERATED by tools/import_boss_levels.py from QuestieDB (GPLv3, https://github.com/Questie/QuestieDB).",
    "-- [instanceID] = { [bossName] = { minLevel, maxLevel, rank } }  (rank 1 = elite, 2 = rare elite, 3 = boss)",
    "",
    "local _, ns = ...",
    "",
    "ns.BOSS_LEVELS = {",
]
for inst in sorted(out):
    lines.append(f"    [{inst}] = {{")
    for name, (lo, hi, rank) in out[inst].items():
        key = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        ["{key}"] = {{ {lo}, {hi}, {rank} }},')
    lines.append("    },")
lines += ["}", ""]
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print(f"levels for {sum(len(v) for v in out.values())} bosses, missing {len(missing)}:")
for inst, name in missing:
    print(f"  {inst}: {name}")
