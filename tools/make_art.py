"""Build ForeverDungeonMap/Data/Art.lua: Blizzard textures that exist in the
WoW Forever client (build 1.60.1.70938), by FileDataID.

Inputs are wago.tools file listings for that build (JSON {fdid: path}):
    GET https://wago.tools/api/files?search=interface/encounterjournal&version=1.60.1.70938
    GET https://wago.tools/api/files?search=interface/glues/loadingscreens&version=1.60.1.70938

Usage:
    python -I tools/make_art.py <encounterjournal.json> <loadingscreens.json> <Generated.lua> <out Art.lua>
"""
import json
import re
import sys

EJ, LOAD, GENERATED, OUT = sys.argv[1:5]

# instanceID -> (Encounter Journal key, loading screen file name)
DUNGEONS = {
    389: ("ragefirechasm", "loadscreenragefirechasm"),
    43: ("wailingcaverns", "loadscreenwailingcaverns"),
    36: ("deadmines", "loadscreendeadmines"),
    33: ("shadowfangkeep", "loadscreenshadowfangkeep"),
    48: ("blackfathomdeeps", "loadscreenblackfathomdeeps"),
    34: ("thestockade", "loadscreenstormwindstockade"),
    90: ("gnomeregan", "loadscreengnomeregan"),
    47: ("razorfenkraul", "loadscreenrazorfenkraul"),
    189: ("scarletmonastery", "loadscreenscarletmonastery2"),
    129: ("razorfendowns", "loadscreenrazorfendowns"),
    70: ("uldaman", "loadscreenuldaman"),
    209: ("zulfarrak", "loadscreenzulfarrak"),
    349: ("maraudon", "loadscreenmaraudon"),
    109: ("sunkentemple", "loadscreensunkentemple"),
    230: ("blackrockdepths", "loadscreenblackrockdepths"),
    229: ("blackrockspire", "loadscreenblackrockspire"),
    429: ("diremaul", "loadscreendiremaul"),
    289: ("scholomance", "loadscreenscholomance"),
    329: ("stratholme", "loadscreenstrathome"),
    # WoW Forever dungeons: only their loading screens exist (Map.LoadingScreenID ->
    # LoadingScreens.MainImageFileDataID in the client's DB2 points at these files)
    2959: (None, "loadscreen_camelot_dalaran"),
    2999: (None, "loadscreen_camelot_ruinsoflordaeron"),
    2998: (None, "loadscreen_camelot_excavation"),
    3065: (None, "loadscreen_camelot_oldironforge"),
    2970: (None, "loadscreen_thedrownedcity_7963741"),
    3039: (None, "loadscreen_kroldokstronghold_7963780"),
    2994: (None, "loadscreen_alcazprison_7963734"),
    2974: (None, "loadscreen_blackmawhold_7963784"),
    3001: (None, "loadscreen_theshapersterrace_7963783"),
}

# Forever loading screens are 2992x1684 with the painting in the band v = 0.16 .. 0.84
# (grey bars above and below). Subject of each painting, picked by eye:
# instanceID -> (centre u, centre v, icon size as a fraction of the image height)
LS_W, LS_H, LS_TOP, LS_BOTTOM = 2992, 1684, 0.16, 0.84
SUBJECT = {
    2959: (0.64, 0.50, 0.66),   # Dalaran's spires
    2998: (0.50, 0.50, 0.66),   # canyon and dig site
    2999: (0.56, 0.50, 0.66),   # graveyard gate
    3065: (0.50, 0.50, 0.66),   # hall arch with the lantern
    2970: (0.42, 0.48, 0.66),   # sunken gate
    3039: (0.55, 0.50, 0.64),   # stronghold gate
    2994: (0.575, 0.51, 0.60),  # jungle prison temple
    2974: (0.58, 0.46, 0.60),   # beast-skull cave
    3001: (0.62, 0.46, 0.60),   # glowing terrace
}
CARD_ASPECT = (0.68359375 * 256) / (0.7421875 * 128)  # same shape as the classic dungeon cards


def coords(u0, u1, v0, v1):
    return "{ %s }" % ", ".join(f"{c:.4f}".rstrip("0").rstrip(".") for c in (u0, u1, v0, v1))


def forever_coords(inst):
    """cardCoords and iconCoords on a Forever loading screen."""
    cu, cv, size = SUBJECT[inst]
    band = LS_BOTTOM - LS_TOP
    cw = CARD_ASPECT * band * LS_H / LS_W
    u0 = min(max(cu - cw / 2, 0), 1 - cw)
    card = coords(u0, u0 + cw, LS_TOP, LS_BOTTOM)
    hu, hv = size * LS_H / LS_W / 2, size / 2
    v0 = min(max(cv - hv, LS_TOP), LS_BOTTOM - size)
    icon = coords(cu - hu, cu + hu, v0, v0 + size)
    return card, icon

ej = json.load(open(EJ, encoding="utf-8"))
load = json.load(open(LOAD, encoding="utf-8"))


def find(listing, filename):
    """fdid of interface/.../<filename>.blp (exact file name match)."""
    for fdid, path in listing.items():
        base = path.rsplit("/", 1)[-1]
        if base.lower() == filename.lower() + ".blp":
            return int(fdid)
    return None


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


bosses_by_key = {}
for fdid, path in ej.items():
    base = path.rsplit("/", 1)[-1]
    if base.startswith("ui-ej-boss-") and base.endswith(".blp"):
        key = norm(base[len("ui-ej-boss-"):-4])
        bosses_by_key.setdefault(key, int(fdid))

lines = [
    "-- GENERATED by tools/make_art.py - Blizzard textures (FileDataIDs) that exist in the",
    "-- WoW Forever client 1.60.1.70938, from the wago.tools file listing. Do not edit by hand.",
    "-- ns.ART[instanceID] = { card, cardCoords, bg, bgCoords, lore, icon, iconCoords }",
    "--   icon/iconCoords (WoW Forever dungeons): square crop of the loading screen for a round icon",
    "-- ns.BOSS_ART[bossName] = Encounter Journal creature picture (128x64)",
    "",
    "local _, ns = ...",
    "",
    "ns.ART = {",
]
missing = []
for inst, (key, screen) in DUNGEONS.items():
    rec = []
    card = find(ej, f"ui-ej-dungeonbutton-{key}") if key else None
    lore = find(ej, f"ui-ej-lorebg-{key}") if key else None
    shot = find(load, screen)
    if card:
        rec.append(f"card = {card}, cardCoords = {{ 0, 0.68359375, 0, 0.7421875 }}")
    elif shot and inst in SUBJECT:
        rec.append(f"card = {shot}, cardCoords = {forever_coords(inst)[0]}")
    elif shot:
        rec.append(f"card = {shot}, cardCoords = {{ 0.1, 0.9, 0.3, 0.7 }}")
    if shot:
        rec.append(f"bg = {shot}, bgCoords = {{ 0, 1, 0.42, 0.56 }}")
    if lore:
        rec.append(f"lore = {lore}")
    if shot and inst in SUBJECT:
        rec.append(f"icon = {shot}, iconCoords = {forever_coords(inst)[1]}")
    if not rec:
        missing.append(inst)
        continue
    lines.append(f"    [{inst}] = {{ {', '.join(rec)} }},")
lines += ["}", "", "ns.BOSS_ART = {"]

names = []
for line in open(GENERATED, encoding="utf-8"):
    if line.startswith("ns.WINGS"):
        break
    m = re.match(r'\s*\{ name = "((?:[^"\\]|\\.)*)"', line)
    if m:
        names.append(m.group(1).replace('\\"', '"'))
found = 0
for name in dict.fromkeys(names):
    fdid = bosses_by_key.get(norm(name)) or bosses_by_key.get(norm(re.sub(r"^the ", "", name, flags=re.I)))
    if fdid:
        found += 1
        key = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    ["{key}"] = {fdid},')
lines += ["}", ""]
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print(f"dungeons with art: {len(DUNGEONS) - len(missing)}/{len(DUNGEONS)} (missing {missing}); "
      f"boss pictures: {found}/{len(set(names))}")
