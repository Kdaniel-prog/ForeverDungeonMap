"""Import quest experience rewards from QuestieDB (GPLv3, https://github.com/Questie/QuestieDB)
into ForeverDungeonMap/Data/QuestXP.lua.

Usage:
    python -I tools/import_quest_xp.py <luaparser-lib-dir> <xpDB-classic.lua> \
        ForeverDungeonMap/Data/Generated.lua ForeverDungeonMap/Data/QuestXP.lua

<xpDB-classic.lua> is QuestieDB master support/Forever/QuestXP/xpDB-classic.lua
(https://raw.githubusercontent.com/Questie/QuestieDB/master/support/Forever/QuestXP/xpDB-classic.lua);
the copy installed with the QuestieDB addon is the same file. Its lines look like
    [2] = {30, 2450}, -- comment
i.e. [questID] = {questLevel, fullXP}. The file is read as text (never executed).

The quest IDs covered are every `id = N` and every ID inside `pre = { ... }` in
ns.QUESTS of Generated.lua. Output: ns.QUEST_XP[questID] = full XP (no level penalty).
"""
import re
import sys

LUAPARSER_DIR, SOURCE, GENERATED, OUT = sys.argv[1:5]
SOURCE_URL = "https://github.com/Questie/QuestieDB/blob/master/support/Forever/QuestXP/xpDB-classic.lua"
ENTRY = re.compile(r"^\s*\[(\d+)\]\s*=\s*\{\s*(-?\d+)\s*,\s*(-?\d+)\s*\}", re.M)


def quest_ids_from_generated(path):
    """Every quest ID of ns.QUESTS and their previous quests (string literals blanked out)."""
    text = open(path, encoding="utf-8").read()
    text = re.sub(r'"(?:\\.|[^"\\\n])*"', '""', text)
    start = text.index("ns.QUESTS = {")
    end = re.compile(r"^}", re.M).search(text, start).start()
    block = text[start:end]
    ids = set(int(x) for x in re.findall(r"\bid\s*=\s*(\d+)", block))
    for match in re.finditer(r"\bpre\s*=\s*\{([^}]*)\}", block):
        ids.update(int(x) for x in re.findall(r"\d+", match.group(1)))
    return ids


def experience_table(path):
    """{questID: fullXP} for entries with a real level and XP (event quests use -1)."""
    table = {}
    for match in ENTRY.finditer(open(path, encoding="utf-8").read()):
        quest_id, level, experience = (int(x) for x in match.groups())
        if level > 0 and experience > 0:
            table[quest_id] = experience
    return table


def write(experience):
    lines = [
        "-- GENERATED by tools/import_quest_xp.py from QuestieDB (GPLv3, %s). Do not edit." % SOURCE_URL,
        "-- ns.QUEST_XP[questID] = experience at full value (before the player-level penalty).",
        "local _, ns = ...",
        "ns.QUEST_XP = {",
    ]
    for quest_id in sorted(experience):
        lines.append("    %-8s = %d," % ("[%d]" % quest_id, experience[quest_id]))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def verify(count):
    sys.path.insert(0, LUAPARSER_DIR)
    from luaparser import ast, astnodes
    tree = ast.parse(open(OUT, encoding="utf-8").read())
    table = tree.body.body[-1].values[0]
    assert isinstance(table, astnodes.Table) and len(table.fields) == count, "output parse check failed"
    print("output parses with luaparser: %d entries" % len(table.fields))


def main():
    wanted = quest_ids_from_generated(GENERATED)
    source = experience_table(SOURCE)
    experience = {quest_id: source[quest_id] for quest_id in wanted if quest_id in source}
    write(experience)
    missing = sorted(wanted - set(experience))
    print("quests wanted %d, with XP %d, missing %d" % (len(wanted), len(experience), len(missing)))
    if missing:
        print("missing:", " ".join(str(x) for x in missing[:60]))
    verify(len(experience))


if __name__ == "__main__":
    main()
